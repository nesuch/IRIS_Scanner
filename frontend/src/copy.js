// Copy text to the clipboard. Uses the async Clipboard API in secure contexts
// (HTTPS / localhost); falls back to the legacy execCommand path otherwise —
// e.g. when the app is opened over a plain-HTTP LAN address like
// http://192.168.x.x:8080, where navigator.clipboard is unavailable.
export async function copyText(text) {
  try {
    if (navigator.clipboard && window.isSecureContext) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch { /* fall through to the legacy path */ }
  try {
    const ta = document.createElement('textarea');
    ta.value = text;
    ta.setAttribute('readonly', '');
    ta.style.position = 'fixed';
    ta.style.top = '0';
    ta.style.left = '0';
    ta.style.opacity = '0';
    document.body.appendChild(ta);
    ta.focus();
    ta.select();
    const ok = document.execCommand('copy');
    ta.remove();
    return ok;
  } catch {
    return false;
  }
}
